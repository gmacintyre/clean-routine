using System.Text.Json;
using System.Text.Json.Serialization;
using Microsoft.Extensions.Options;

namespace CleanRoutine.Services;

/// <summary>Where data files live. On Azure App Service that's %HOME%/data/clean-routine, which is persistent
/// storage shared across restarts and deploys; locally it's ./App_Data.</summary>
public sealed class DataPaths
{
    public string Root { get; }
    public string AccountsFile => Path.Combine(Root, "accounts.json");
    public string HouseholdsDirectory => Path.Combine(Root, "households");
    public string BackupsDirectory => Path.Combine(Root, "backups");
    /// <summary>The single data file the app used before it was opened up to other households.</summary>
    public string LegacyHouseholdFile => Path.Combine(Root, "household.json");

    public DataPaths(IOptions<StorageOptions> options, IHostEnvironment env, ILogger<DataPaths> log)
    {
        Root = Resolve(options.Value.DataDirectory, env);
        Directory.CreateDirectory(Root);
        Directory.CreateDirectory(HouseholdsDirectory);
        log.LogInformation("Data folder: {Path}", Root);
    }

    public string HouseholdFile(string householdId)
    {
        // Ids are generated by the app (32 hex characters); refuse anything else so an id can never
        // point outside the households folder.
        if (householdId.Length != 32 || !householdId.All(Uri.IsHexDigit))
            throw new ArgumentException("Not a household id.", nameof(householdId));
        return Path.Combine(HouseholdsDirectory, householdId + ".json");
    }

    private static string Resolve(string? configured, IHostEnvironment env)
    {
        if (!string.IsNullOrWhiteSpace(configured)) return configured;
        var home = Environment.GetEnvironmentVariable("HOME");
        if (Environment.GetEnvironmentVariable("WEBSITE_SITE_NAME") is not null && !string.IsNullOrEmpty(home))
            return Path.Combine(home, "data", "clean-routine");
        return Path.Combine(env.ContentRootPath, "App_Data");
    }
}

internal static class StoreJson
{
    public static readonly JsonSerializerOptions Options = new(JsonSerializerDefaults.Web)
    {
        WriteIndented = true,
        Converters = { new JsonStringEnumConverter() },
    };
}

/// <summary>
/// One JSON file held in memory. Every read and write goes through a lock, so two people checking things
/// off at the same moment can't overwrite each other. Writes go to a temp file first and are then swapped in.
/// The first write each day also copies the previous version to backups/yyyy-MM-dd/.
/// </summary>
internal sealed class JsonFile<T> where T : class, new()
{
    private const int BackupDays = 14;
    private static DateOnly _lastPrune;

    private readonly string _path;
    private readonly string _backupRoot;
    private readonly Func<T, bool>? _onLoad;
    private readonly ILogger _log;
    private T? _data;
    private DateOnly _lastBackup;

    public SemaphoreSlim Lock { get; } = new(1, 1);
    /// <summary>Set once the file has been dropped from memory; callers holding it must open it again.</summary>
    public bool Closed { get; set; }
    public DateTime LastUsedUtc { get; private set; } = DateTime.UtcNow;

    /// <param name="onLoad">Runs after loading; return true if it changed the data and it should be saved.</param>
    public JsonFile(string path, string backupRoot, ILogger log, Func<T, bool>? onLoad = null)
    {
        _path = path;
        _backupRoot = backupRoot;
        _log = log;
        _onLoad = onLoad;
    }

    /// <summary>Call while holding <see cref="Lock"/>.</summary>
    public async Task<T> LoadAsync()
    {
        LastUsedUtc = DateTime.UtcNow;
        if (_data is not null) return _data;

        if (File.Exists(_path))
        {
            await using var stream = File.OpenRead(_path);
            _data = await JsonSerializer.DeserializeAsync<T>(stream, StoreJson.Options)
                    ?? throw new InvalidDataException($"{_path} is empty or not valid.");
        }
        else
        {
            _data = new T();
        }

        if (_onLoad?.Invoke(_data) == true) await SaveAsync(_data);
        return _data;
    }

    /// <summary>Call while holding <see cref="Lock"/>.</summary>
    public async Task SaveAsync(T data)
    {
        BackupOncePerDay();
        var temp = _path + ".tmp";
        await using (var stream = File.Create(temp))
        {
            await JsonSerializer.SerializeAsync(stream, data, StoreJson.Options);
        }
        File.Move(temp, _path, overwrite: true);
    }

    public async Task<TResult> ReadAsync<TResult>(Func<T, TResult> read)
    {
        await Lock.WaitAsync();
        try { return read(await LoadAsync()); }
        finally { Lock.Release(); }
    }

    public async Task<TResult> WriteAsync<TResult>(Func<T, TResult> change)
    {
        await Lock.WaitAsync();
        try
        {
            var data = await LoadAsync();
            var result = change(data);
            await SaveAsync(data);
            return result;
        }
        finally { Lock.Release(); }
    }

    private void BackupOncePerDay()
    {
        var today = DateOnly.FromDateTime(DateTime.UtcNow);
        if (_lastBackup == today) return;
        try
        {
            if (!File.Exists(_path)) return;
            var dir = Path.Combine(_backupRoot, today.ToString("yyyy-MM-dd"));
            Directory.CreateDirectory(dir);
            var target = Path.Combine(dir, Path.GetFileName(_path));
            if (!File.Exists(target)) File.Copy(_path, target);
            _lastBackup = today;
            PruneOldBackups(today);
        }
        catch (Exception ex)
        {
            _log.LogWarning(ex, "Could not back up {Path}.", _path);
        }
    }

    private void PruneOldBackups(DateOnly today)
    {
        if (_lastPrune == today) return;
        _lastPrune = today;
        foreach (var dir in Directory.GetDirectories(_backupRoot).OrderDescending().Skip(BackupDays))
            Directory.Delete(dir, recursive: true);
    }
}
